#!/usr/bin/env kotlin

// === ИНФРАСТРУКТУРА (Подешавање да би твој код радио) ===

// 'сада' је променљива која, када год је позовеш, враћа тренутно време у милисекундама
val сада: Long
    get() = System.currentTimeMillis()

// Функција за чекање која пази да не чека негативно време (ако програм касни)
fun чекај(време: Long) {
    if (време > 0) {
        Thread.sleep(време)
    }
}

// Функција која рачуна колико реч треба да траје
// (нпр. 200 милисекунди за свако слово у речи)
fun трајање(реч: String): Long {
    return (реч.length * 200).toLong()
}

// Наш стари познаник, infix функција за лепши испис
object пређи {
    infix fun на(реч: String) {
        println("-> $реч")
    }
}

val текстЗаЧитање = listOf("Ово", "је", "проба", "динамичког", "читања", "текста.")

println("Почињем читање...\n")



var следећа_смена = сада
for (текућа_реч in текстЗаЧитање) {
    следећа_смена = следећа_смена + трајање(текућа_реч)
    чекај(следећа_смена - сада)
    пређи на текућа_реч
}

println("\nКрај читања!")